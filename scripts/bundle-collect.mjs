// Builds a single-file version of the `collect` Edge Function for pasting into
// the Supabase dashboard editor (which takes one file). Concatenates the shared
// modules and the entry point, dropping the relative imports between them.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const fn = (p) => readFileSync(join(root, "supabase/functions", p), "utf8");
const dropRelativeImports = (src) =>
  src.replace(/^import\s+(?:type\s+)?\{[^}]*\}\s+from\s+"\.{1,2}\/[^"]+";\s*$/gms, "");

const parts = [
  ["_shared/normalize.ts", fn("_shared/normalize.ts")],
  ["_shared/alerts.ts", fn("_shared/alerts.ts")],
  ["_shared/collector.ts", fn("_shared/collector.ts")],
  ["collect/index.ts", fn("collect/index.ts")],
];

// The npm import must sit at the top of the module.
const entry = dropRelativeImports(parts[parts.length - 1][1]);
const npmImport = entry.match(/^import .* from "npm:[^"]+";$/m)[0];

const out = [
  "// PoE Economy Tools — Edge Function `collect` (single-file build for the Supabase dashboard).",
  "// Generated by scripts/bundle-collect.mjs — do not edit by hand.",
  npmImport,
  ...parts.map(([name, src]) => `\n// ===== ${name} =====\n${dropRelativeImports(src).replace(npmImport, "")}`),
].join("\n");

if (/from\s+"\.{1,2}\//.test(out)) throw new Error("a relative import survived bundling");
const target = join(root, "dist/collect.single.ts");
mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, out);
console.log(`wrote ${target} (${out.length} bytes)`);
